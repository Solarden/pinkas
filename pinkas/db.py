"""The tables as the queries see them, and the helpers that run SQLAlchemy Core statements on a psycopg2 cursor.

The migrations own the schema: these declare the columns, with no keys, constraints or grants. A declared
primary key would make SQLAlchemy add RETURNING to an INSERT, to fetch the new row's key.
"""

import sqlalchemy as sa
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.dialects.postgresql.psycopg2 import dialect

TS = sa.DateTime(timezone=True)
# The driver the connections already are, so a compiled statement runs on their cursors as it is.
DIALECT = dialect()
# `data -> 'key'`, as Debian trixie's SQLAlchemy 2.0.40 writes it; later 2.0 releases write `data['key']`.
DIALECT._supports_jsonb_subscripting = False
metadata = sa.MetaData()

files = sa.Table(
    "pinkas_files", metadata,
    sa.Column("id", sa.BigInteger),
    sa.Column("sha256", sa.Text),
    sa.Column("fetched_at", TS),
    sa.Column("body", sa.LargeBinary),
)
characters = sa.Table(
    "pinkas_characters", metadata,
    sa.Column("id", sa.Integer),
    sa.Column("realm", sa.Text),
    sa.Column("name", sa.Text),
    sa.Column("role", sa.Text),
    sa.Column("sort", sa.Integer),
    sa.Column("well_rested_rank", sa.SmallInteger),
    sa.Column("archived_at", TS),
    sa.Column("playing_since", TS),
)
snapshots = sa.Table(
    "pinkas_snapshots", metadata,
    sa.Column("id", sa.BigInteger),
    sa.Column("character_id", sa.Integer),
    sa.Column("logout_at", TS),
    sa.Column("session_started_at", TS),
    sa.Column("data", JSONB),
    sa.Column("file_id", sa.BigInteger),
    # Generated by Postgres from `data` (migration 0003): read, never written.
    sa.Column("level", sa.Integer),
    sa.Column("xp", sa.Integer),
    sa.Column("xp_max", sa.Integer),
    sa.Column("money", sa.BigInteger),
    sa.Column("professions", JSONB),
    sa.Column("mats", JSONB),
)
targets = sa.Table(
    "pinkas_targets", metadata,
    sa.Column("id", sa.Integer),
    sa.Column("character_id", sa.Integer),
    sa.Column("skill_line", sa.Integer),
    sa.Column("skill", sa.SmallInteger),
)
pull_state = sa.Table(
    "pinkas_pull_state", metadata,
    sa.Column("id", sa.Boolean),
    sa.Column("status", sa.Text),
    sa.Column("since", TS),
)
events = sa.Table(
    "pinkas_events", metadata,
    sa.Column("id", sa.BigInteger),
    sa.Column("character_id", sa.Integer),
    sa.Column("event_id", sa.Integer),
    sa.Column("at", TS),
    sa.Column("kind", sa.Text),
    sa.Column("value", JSONB),
)
session_totals = sa.Table(
    "pinkas_session_totals", metadata,
    sa.Column("id", sa.BigInteger),
    sa.Column("character_id", sa.Integer),
    sa.Column("session_started_at", TS),
    sa.Column("kind", sa.Text),
    sa.Column("key", sa.Text),
    sa.Column("value", JSONB),
    sa.Column("exported_at", TS),
)
guide = sa.Table(
    "pinkas_guide", metadata,
    sa.Column("id", sa.Boolean),
    sa.Column("text", sa.Text),
    sa.Column("updated_at", TS),
)
routes = sa.Table(
    "pinkas_routes", metadata,
    sa.Column("kind", sa.Text),
    sa.Column("character_id", sa.Integer),
)

# Each character's newest snapshot as `s`, walking the (character_id, logout_at) unique index. Joined to
# pinkas_characters by `WITH_NEWEST`.
NEWEST = (
    sa.select(snapshots.c.logout_at, snapshots.c.data).where(snapshots.c.character_id == characters.c.id)
    .order_by(snapshots.c.logout_at.desc()).limit(1).lateral("s")
)
WITH_NEWEST = characters.join(NEWEST, sa.true())


def execute(cur, statement, args: dict | None = None) -> None:
    """Every value goes as a bound parameter; `args` fills the statement's named `bindparam`s.

    The values reach psycopg2 as they are, without SQLAlchemy's type processing: a JSONB value is wrapped
    in psycopg2's `Json`.
    """
    compiled = statement.compile(dialect=DIALECT)
    cur.execute(str(compiled), compiled.construct_params(args))


def fetch(cur, statement, args: dict | None = None) -> list[dict]:
    execute(cur, statement, args)
    names = [d.name for d in cur.description]

    return [dict(zip(names, row, strict=True)) for row in cur.fetchall()]
